# Generates a live-cluster e2e for every workload that can boot from its own
# published image, driven entirely by the catalog. For each workload it emits a
# `hack/smoke/scenario-<id>.sh` (boot every stage, wait for health) and a thin
# `.github/workflows/e2e-<id>.yml` (self-gated on the workload's paths, delegating
# to the reusable e2e workflow) — the same shape the hand-written scenarios use,
# so `gen-maturity` lifts each covered workload to the `e2e` tier automatically.
#
# It touches ONLY generated files: a scenario carrying the marker below is
# regenerated in place, one lacking it (a hand-authored scenario like tik's) is
# left untouched. This pass covers the workloads a consumer can boot with no
# external dependency — those whose `requires` is empty and whose stages ship a
# real image. Dependency-backed workloads (database/cache/objectStorage) are
# provisioned by a later pass and are skipped here, listed in the run summary.
set -euo pipefail
# Run from the repository root (as the flake's `gen-smoke` command does), matching
# the sibling gen-* scripts — paths below are repo-relative.

# Assemble the SPDX tag names from parts so the literal tokens never appear whole
# in this generator's source — otherwise REUSE reads the header lines this script
# PRINTS as (invalid, duplicated) license expressions of the script itself.
spdx_copy='SPDX-File''CopyrightText'
spdx_lic='SPDX-License''-Identifier'

marker='# generated by scripts/gen-smoke.sh — do not edit; regenerate with: gen-smoke'
catalog=catalog/catalog.json
[ -f "$catalog" ] || { echo "::error::$catalog missing — run gen-catalog first"; exit 1; }

generated=0 skipped_dep=0 skipped_hand=0

# Standalone, real-image workloads: empty `requires`, at least one stage with a
# real (non-operator) image. Emit "id<TAB>stage1,stage2,...".
while IFS=$'\t' read -r id stages; do
  [ -n "$id" ] || continue
  scenario="hack/smoke/scenario-${id}.sh"
  if [ -f "$scenario" ] && ! grep -qF "$marker" "$scenario"; then
    skipped_hand=$((skipped_hand + 1))
    continue
  fi

  # Boot each stage in its own namespace; a single-stage workload gets the bare
  # kurly-<id> namespace, multi-stage workloads suffix the stage.
  boot_lines=""
  IFS=',' read -ra arr <<<"$stages"
  for stage in "${arr[@]}"; do
    file="workloads/${id}/${stage}.libsonnet"
    [ -f "$file" ] || { echo "::error::${file} referenced by the catalog does not exist"; exit 1; }
    if [ "${#arr[@]}" -eq 1 ]; then ns="kurly-${id}"; else ns="kurly-${id}-${stage}"; fi
    boot_lines+="kurly::boot ${file} ${ns}"$'\n'
  done

  {
    printf '#!/usr/bin/env bash\n'
    printf '# %s: The kurly Authors\n' "$spdx_copy"
    printf '# %s: 0BSD\n\n' "$spdx_lic"
    printf '%s\n' "$marker"
    printf '# e2e for the %s workload: boot every stage on a live kind cluster from its\n' "$id"
    printf '# own published image and wait for it to become healthy. No external dependency.\n'
    printf 'cd "$(dirname "$0")/../.."\n'
    printf '# shellcheck source=hack/smoke/lib.sh\n'
    printf 'source hack/smoke/lib.sh\n'
    printf 'kurly::vendor\n\n'
    printf '%s' "$boot_lines"
  } >"$scenario"
  chmod +x "$scenario"

  workflow=".github/workflows/e2e-${id}.yml"
  {
    printf '# %s: The kurly Authors\n' "$spdx_copy"
    printf '# %s: 0BSD\n\n' "$spdx_lic"
    printf '%s\n' "$marker"
    printf '# Per-workload e2e for %s. Self-gates on a diff scoped to this workload (plus the\n' "$id"
    printf '# shared library and the e2e machinery), delegating the matrix + run to the\n'
    printf '# reusable e2e workflow.\n'
    printf 'name: E2E %s\n' "$id"
    printf 'on:\n  pull_request:\n    branches: [main]\n  workflow_dispatch:\n'
    printf 'permissions:\n  contents: read\n'
    # A constant job id keeps it valid for workloads whose name starts with a
    # digit (e.g. 2fauth), which is not a legal job identifier.
    printf 'jobs:\n  e2e:\n'
    printf '    uses: ./.github/workflows/e2e.yml\n'
    printf '    with:\n'
    printf '      workload: %s\n' "$id"
    # The paths regex can exceed yamllint's line length for long workload names;
    # it is a single unbreakable token, so silence the one rule on that line.
    printf '      # yamllint disable-line rule:line-length\n'
    printf "      paths: '^(workloads/%s/|lib/|main\\\\.libsonnet|hack/smoke/(lib|scenario-%s)\\\\.sh|\\\\.github/workflows/e2e(-%s)?\\\\.yml)'\n" "$id" "$id" "$id"
    printf '      scenario: hack/smoke/scenario-%s.sh\n' "$id"
  } >"$workflow"

  generated=$((generated + 1))
done < <(jq -r '
  .workloads[]
  | select((.requires // {} | length) == 0)
  | select([.stages[].architectures] | any(. != null))
  | "\(.id)\t\([.stages[].id] | join(","))"
' "$catalog")

# Report the dependency-backed workloads this pass deliberately leaves for the
# provisioning pass, so the coverage gap is never silently hidden.
skipped_dep=$(jq -r '[.workloads[] | select((.requires // {} | length) > 0)] | length' "$catalog")

# A durable coverage ledger for the "e2e for every workload" effort — regenerated
# every run so it never drifts, and readable across working sessions. Each
# workload is either covered (a scenario boots it) or awaiting the dependency
# provisioning pass, grouped by what it still needs.
{
  printf '<!-- %s: The kurly Authors -->\n' "$spdx_copy"
  printf '<!-- %s: 0BSD -->\n\n' "$spdx_lic"
  printf '<!-- generated by scripts/gen-smoke.sh — do not edit -->\n\n'
  printf '# e2e coverage\n\n'
  printf 'An e2e scenario boots every workload on a live kind cluster. Standalone\n'
  printf 'workloads are generated by `gen-smoke`; dependency-backed workloads are\n'
  printf 'provisioned per pass and tracked here until covered.\n\n'
  total=$(jq '.workloads | length' "$catalog")
  cov=$(jq '[.workloads[] | select(.maturity.tier == "e2e")] | length' "$catalog")
  printf '**%s / %s workloads have an e2e scenario.**\n\n' "$cov" "$total"
  printf '## Awaiting the dependency provisioning pass\n\n'
  printf '| workload | needs |\n| --- | --- |\n'
  jq -r '
    .workloads[]
    | select(.maturity.tier != "e2e")
    | . as $w
    | [ (if .requires.database then "database" + (if .requires.database=="optional" then "?" else "" end) else empty end),
        (if .requires.cache then "cache" + (if .requires.cache=="optional" then "?" else "" end) else empty end),
        (if .requires.objectStorage then "objectStorage" + (if .requires.objectStorage=="optional" then "?" else "" end) else empty end) ] as $needs
    | "| \(.id) | \(if ($needs|length)>0 then ($needs|join(", ")) else "operator (custom resource)" end) |"
  ' "$catalog" | sort
} >hack/smoke/COVERAGE.md

echo "gen-smoke: generated ${generated} standalone scenarios + workflows"
echo "gen-smoke: left ${skipped_hand} hand-written scenarios untouched"
echo "gen-smoke: ${skipped_dep} dependency-backed workloads await the provisioning pass"
echo "gen-smoke: wrote hack/smoke/COVERAGE.md"
